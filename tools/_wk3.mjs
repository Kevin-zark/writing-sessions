import { webkit, devices } from 'playwright';
const b = await webkit.launch(); const ctx = await b.newContext({ ...devices['iPhone 14'] }); const p = await ctx.newPage();
await p.addInitScript(() => { window.__vev = []; const orig = HTMLMediaElement.prototype.load; ['error','canplay','loadeddata','playing','ended','stalled','abort','emptied'].forEach(e => document.addEventListener(e, ev => window.__vev.push(e + ':' + (ev.target.currentSrc||'').split('/').pop() + (ev.target.error ? ' code' + ev.target.error.code + ' ' + ev.target.error.message : '') + '@' + Math.round(performance.now())), true)); });
p.on('pageerror', e => console.log('PAGEERR', e.message)); p.on('console', m => console.log('console', m.type(), m.text()));
const t0 = Date.now();
await p.goto(process.argv[2] || 'http://localhost:8099/'); await p.waitForSelector('.card-theme'); await p.click('.card-theme'); await p.click('#begin');
await p.waitForFunction(() => window.__ws && window.__ws.started, null, { timeout: 60000 });
console.log('started after', Date.now() - t0);
await p.waitForTimeout(6000);
console.log(await p.evaluate(() => JSON.stringify({ ev: window.__vev, log: window.__ws.stage.log })));
await b.close();
